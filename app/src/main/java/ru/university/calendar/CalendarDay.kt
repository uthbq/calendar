package ru.university.calendar

// Модель одной ячейки в календарной сетке месяца (используется в MainActivity и CalendarAdapter).
//
// Ключевое слово `data class` в Kotlin — это специальный класс именно для хранения данных:
// компилятор сам автоматически дописывает за нас методы equals() (сравнение по полям),
// hashCode(), toString() (красивый вывод в логах) и copy() (удобное копирование с заменой пары полей).
//
// Все поля объявлены через `val` (неизменяемые), чтобы никто случайно не поменял данные ячейки в процессе отрисовки.
// У последних четырёх полей указаны значения по умолчанию (`= 0`, `= false`), поэтому для пустой клетки
// в начале месяца достаточно просто написать `CalendarDay(date = null)`, не перечисляя все остальные поля вручную.
data class CalendarDay(
    // Полная дата ячейки в формате "yyyy-MM-dd" (например, "2026-11-24").
    // Тип `String?` со знаком вопроса — значит может быть null:
    // так я помечаю пустые клетки-отступы перед 1-м числом месяца (если месяц начинается не с понедельника)
    val date: String?,

    // Само число месяца, которое рисуется внутри клетки (от 1 до 31; для пустой клетки остаётся 0)
    val dayNumber: Int = 0,

    // true, если эта клетка соответствует сегодняшней дате на телефоне (рисуем вокруг неё обводку)
    val isToday: Boolean = false,

    // true, если пользователь сейчас выбрал именно этот день (закрашиваем кружок полностью)
    val isSelected: Boolean = false,

    // true, если в базе Room на эту дату есть хотя бы одна задача (показываем цветную точку под числом)
    val hasTasks: Boolean = false
)