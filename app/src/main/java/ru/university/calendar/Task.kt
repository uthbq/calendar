// Адрес (пакет) моего приложения — все файлы в этой папке видят класс Task без лишних импортов
package ru.university.calendar

// Аннотации из библиотеки Room:
// @Entity — превращает обычный класс Kotlin в таблицу базы данных SQLite;
// @PrimaryKey — отмечает поле, которое будет главным уникальным номером каждой строки в таблице
import androidx.room.Entity
import androidx.room.PrimaryKey

// Главная модель данных приложения — описывает одну задачу (в архитектуре MVVM это слой Model).
//
// Аннотация @Entity(tableName = "tasks_table") говорит Room создать в базе SQLite таблицу
// с именем "tasks_table", где каждое поле этого класса автоматически станет отдельным столбцом.
//
// Почему именно `data class`, а не обычный `class`?
// В Kotlin `data class` предназначен специально для хранения данных — компилятор сам дописывает
// за нас полезные методы: equals() (сравнение двух задач по полям), hashCode(), toString() (удобный вывод в лог)
// и copy() (например, в MainActivity я легко делаю `task.copy(isDone = isChecked)`, чтобы поменять только галочку).
//
// Все поля объявлены через `val` (неизменяемые), чтобы объект задачи нельзя было случайно поломать в процессе работы.
@Entity(tableName = "tasks_table")
data class Task(
    // Аннотация @PrimaryKey помечает это поле как первичный ключ (уникальный идентификатор строки).
    // Параметр `autoGenerate = true` означает, что SQLite сама будет выдавать каждой новой задаче
    // следующий свободный номер (1, 2, 3...), если мы передадим при создании `id = 0` (значение по умолчанию)
    @PrimaryKey(autoGenerate = true)
    val id: Int = 0,

    // Название задачи — обязательное поле (без значения по умолчанию, так как задача не может быть без названия)
    val title: String,

    // Подробное описание задачи — необязательное, поэтому по умолчанию пустая строка ""
    val description: String = "",

    // Дата выполнения задачи — хранится строкой в едином формате "yyyy-MM-dd" (например, "2026-11-24").
    // Такой формат удобен тем, что календарь точно ищет задачи за день по совпадению строки,
    // а текстовая сортировка ORDER BY date ASC сама идёт в правильном календарном порядке
    val date: String,

    // Время напоминания в формате "HH:mm" (например, "14:30").
    // Если пользователь время не выбрал, тут хранится пустая строка "" — тогда уведомление не планируется
    val time: String = "",

    // Статус выполнения задачи (false — в работе, true — выполнена).
    // Под капотом SQLite не имеет отдельного типа Boolean, поэтому Room сам сохраняет false как 0, а true как 1
    val isDone: Boolean = false,

    // Категория/тег задачи ("Личное", "Учёба", "Работа" и т.д.). По умолчанию ставится "Личное"
    val category: String = "Личное",

    // Уровень приоритета: 0 — Низкий, 1 — Средний (по умолчанию), 2 — Высокий.
    // Храню именно числом, а не словом, чтобы в SQL можно было легко сортировать важные задачи наверх (ORDER BY priority DESC)
    val priority: Int = 1
)