// Адрес (пакет) моего приложения — все классы внутри папки ru.university.calendar видят друг друга без лишних импортов
package ru.university.calendar

// Встроенные в Android классы для работы с форматом JSON (специально взял их, а не сторонний Gson,
// чтобы не тащить лишние библиотеки в build.gradle — всё работает из коробки):
// JSONArray — это список [...] в JSON;
// JSONObject — это один объект {...} с парами «ключ: значение»
import org.json.JSONArray
import org.json.JSONObject

// Помощник для резервного копирования: переводит список наших задач в текст JSON (для экспорта в файл)
// и обратно из текста JSON в список объектов Task (для импорта из файла).
// Сделан через `object` (одиночный объект на всё приложение), чтобы не писать каждый раз `TaskJsonHelper()`,
// а сразу вызывать `TaskJsonHelper.tasksToJson(...)` и `TaskJsonHelper.jsonToTasks(...)` из TaskViewModel.
object TaskJsonHelper {

    // Берёт обычный список задач из базы Room и собирает из него красивую строку в формате JSON,
    // которую потом можно сохранить в файл tasks_backup.json
    fun tasksToJson(tasks: List<Task>): String {
        // Создаём пустой JSON-массив, куда будем по одной складывать все задачи
        val jsonArray = JSONArray()

        // Пробегаемся циклом по каждой задаче из переданного списка
        for (task in tasks) {
            // Для каждой задачи создаём отдельный JSONObject и через `.apply { ... }` сразу наполняем его полями.
            // Обрати внимание: поле `id` мы сюда специально НЕ записываем!
            // Почему: ID — это внутренний номер строки в конкретной базе. При переносе бэкапа на другой телефон
            // или при восстановлении в текущую базу Room сам выдаст новым задачам свежие уникальные ID без конфликтов
            val obj = JSONObject().apply {
                put("title", task.title)
                put("description", task.description)
                put("date", task.date)
                put("time", task.time)
                put("isDone", task.isDone)
                put("category", task.category)
                put("priority", task.priority)
            }
            // Добавляем собранный JSON-объект задачи в общий массив
            jsonArray.put(obj)
        }

        // Превращаем массив в готовый текст.
        // Число `2` внутри toString(2) задаёт отступ в 2 пробела — благодаря этому файл получается
        // аккуратным, многострочным и легко читается глазами, если открыть его в обычном блокноте
        return jsonArray.toString(2)
    }

    // Обратная функция: разбирает текст из JSON-файла обратно в список объектов Task.
    // Возвращает `List<Task>?` со знаком вопроса — значит может вернуть null,
    // если файл повреждён, пустой или пользователь случайно выбрал вообще не JSON-файл
    fun jsonToTasks(json: String): List<Task>? {
        // Оборачиваем весь разбор в `try / catch`, потому что JSON-файл приходит снаружи (с телефона пользователя)
        // и в нём может быть любой мусор — нельзя, чтобы приложение упало с ошибкой
        return try {
            // Пробуем прочитать строку как JSON-массив `[...]`. Если формат сломан, сразу прыгнем в блок `catch`
            val jsonArray = JSONArray(json)
            // Сюда будем складывать успешно разобранные задачи (`mutableListOf` — изменяемый список)
            val result = mutableListOf<Task>()

            // Идём по индексам от 0 до последнего элемента массива (`until` значит «не включая length()»)
            for (i in 0 until jsonArray.length()) {
                // Достаём i-й JSON-объект одной задачи
                val obj = jsonArray.getJSONObject(i)

                // Используем именно `optString(...)`, а не `getString(...)`!
                // Разница важная: `getString` сразу бросит ошибку и сломает импорт, если поля нет в файле,
                // а `optString("ключ", "запасное значение")` спокойно вернёт пустую строку "".
                // `.trim()` убирает случайные пробелы по краям
                val title = obj.optString("title", "").trim()
                val date = obj.optString("date", "").trim()

                // Если в файле попалась битая запись без названия или без даты — просто пропускаем её (`continue`)
                // и переходим к следующей задаче, не ломая весь импорт
                if (title.isEmpty() || date.isEmpty()) continue

                // Собираем нормальный объект Task и добавляем его в итоговый список.
                // Для необязательных полей (описание, время, статус, категория, приоритет) тоже берём `opt...`
                // с понятными значениями по умолчанию — так старый бэкап (даже без новых полей) спокойно загрузится
                result.add(
                    Task(
                        id = 0, // Ставим 0, чтобы Room сам выдал новые уникальные ID при вставке в базу
                        title = title,
                        description = obj.optString("description", ""),
                        date = date,
                        time = obj.optString("time", ""),
                        isDone = obj.optBoolean("isDone", false),
                        category = obj.optString("category", "Личное"),
                        // `.coerceIn(0, 2)` страхует от кривых чисел в файле (если кто-то руками написал priority: 99, станет 2)
                        priority = obj.optInt("priority", 1).coerceIn(0, 2)
                    )
                )
            }
            // Последняя строка блока `try` возвращается наружу как результат функции
            result
        } catch (_: Exception) {
            // Если на любом шаге разбора случилась ошибка (знак `_` — сам объект ошибки не нужен),
            // возвращаем null — по нему MainActivity поймёт, что надо показать Toast «некорректный JSON-файл»
            null
        }
    }
}