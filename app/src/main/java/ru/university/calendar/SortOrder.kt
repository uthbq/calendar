package ru.university.calendar

// Перечисление (`enum class`) всех доступных режимов сортировки списка задач.
//
// Зачем делать отдельный enum вместо обычных чисел (0, 1, 2, 3) или строк ("date", "title"):
// С enum невозможно опечататься в названии или передать несуществующий режим — компилятор сам проверит,
// что в `when` (в TaskRepository и MainActivity) обработаны абсолютно все варианты.
// Используется в связке: MainActivity (выбор в диалоге) -> TaskViewModel (хранение текущего режима) ->
// TaskRepository (выбор нужного SQL-запроса ORDER BY в TaskDao).
enum class SortOrder {
    // По дате и времени (сначала ближайшие задачи; задачи без указанного времени уходят в конец дня)
    BY_DATE,

    // По алфавиту (от А до Я по названию задачи без учёта регистра букв)
    BY_TITLE,

    // По статусу выполнения (сначала активные невыполненные задачи, выполненные уходят вниз)
    BY_STATUS,

    // По приоритету (сначала Высокий = 2, затем Средний = 1, затем Низкий = 0)
    BY_PRIORITY
}