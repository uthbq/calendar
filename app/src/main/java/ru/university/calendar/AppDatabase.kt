// Адрес (пакет) моего приложения
package ru.university.calendar

// Context нужен Room, чтобы понять, в какой системной папке телефона создать файл базы SQLite
import android.content.Context

// Аннотация и классы библиотеки Room (удобная обёртка над обычным SQLite от Google)
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase

// Главный класс локальной базы данных приложения (в архитектуре MVVM это слой Model / Data).
//
// Аннотация @Database рассказывает Room, из чего состоит наша база:
// - `entities = [Task::class]` — список всех таблиц в базе (у нас одна таблица — Task);
// - `version = 3` — номер версии структуры базы. Каждый раз, когда я добавлял новые поля в Task
//   (сначала время, потом категорию и приоритет), я увеличивал версию на 1, чтобы Room знал, что схема поменялась;
// - `exportSchema = false` — не сохранять историю схем базы в отдельные JSON-файлы проекта.
//
// Класс объявлен как `abstract`, потому что мы сами не пишем код открытия SQLite и выполнения SQL —
// при сборке проекта Room автоматически сгенерирует реальный класс-наследник с готовым кодом.
@Database(entities = [Task::class], version = 3, exportSchema = false)
abstract class AppDatabase : RoomDatabase() {

    // Абстрактный метод, через который Room предоставит нам доступ к методам DAO
    // (реализацию этого метода Room тоже сгенерирует сам во время сборки)
    abstract fun taskDao(): TaskDao

    // `companion object` — блок «общих» полей и методов класса (в Java это называется `static`).
    // Благодаря ему мы можем получить базу из любого места просто написав `AppDatabase.getDatabase(context)`,
    // не создавая объект AppDatabase вручную.
    companion object {
        // Здесь хранится единственный на всё приложение экземпляр базы данных (паттерн Singleton / Одиночка).
        // Зачем делать базу в единственном экземпляре?
        // Открывать подключение к SQLite — тяжёлая операция для памяти; плюс если открыть сразу много баз,
        // они могут конфликтовать при одновременной записи.
        //
        // Аннотация `@Volatile` нужна для безопасности при работе из разных потоков:
        // как только один поток запишет сюда созданную базу, все остальные потоки мгновенно это увидят
        // (а не возьмут устаревший null из своего кэша).
        // Тип `AppDatabase?` со знаком вопроса, потому что до первого обращения тут лежит null
        @Volatile
        private var INSTANCE: AppDatabase? = null

        // Метод для получения единого экземпляра базы данных
        fun getDatabase(context: Context): AppDatabase {
            // Если база уже была создана раньше (INSTANCE не null) — сразу возвращаем её.
            // Если там null — срабатывает правая часть после `?:`.
            // Блок `synchronized(this)` работает как «замок на двери»: одновременно внутрь может зайти
            // только один поток. Это страхует от редкой ситуации, когда два потока одновременно увидят null
            // и случайно создадут две одинаковые базы данных
            return INSTANCE ?: synchronized(this) {
                // Собираем базу данных через строитель Room.databaseBuilder:
                // 1) `context.applicationContext` — берём именно контекст всего приложения, а НЕ конкретного экрана (Activity).
                //    Если передать сюда Activity, база будет держать её в памяти даже после закрытия экрана (утечка памяти);
                // 2) `AppDatabase::class.java` — указываем наш класс базы;
                // 3) `"task_database"` — имя реального файла базы данных внутри памяти телефона.
                //
                // `.fallbackToDestructiveMigration()` — говорит Room: если версия базы выросла (например, с 2 до 3),
                // а ручных правил переноса данных нет, просто пересоздай таблицу с нуля вместо того, чтобы ронять приложение.
                // `.build()` — окончательно создаёт готовый объект базы
                val instance = Room.databaseBuilder(
                    context.applicationContext,
                    AppDatabase::class.java,
                    "task_database" // Имя файла базы данных на устройстве
                ).fallbackToDestructiveMigration().build()

                // Сохраняем созданную базу в INSTANCE, чтобы при следующих вызовах отдавать уже готовую
                INSTANCE = instance
                // Последняя строка внутри блока `synchronized` — это возвращаемое значение
                instance
            }
        }
    }
}