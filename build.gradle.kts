// Глобальный файл проекта (лежит в самом корне репозитория).
// Его задача — один раз в одном месте задать точные версии главных плагинов сборки для всего проекта,
// чтобы все модули (у нас это модуль :app) использовали согласованные между собой версии.
//
// Зачем в конце каждой строчки написано `apply false`?
// Это говорит Gradle: «скачай и запомни версию этого плагина для проекта, но НЕ применяй его
// к самой корневой папке — его подключат у себя конкретные подмодули (внутри app/build.gradle.kts)».
plugins {
    // Android Gradle Plugin (AGP 8.2.0) — главный движок, который умеет собирать Android-приложения
    id("com.android.application") version "8.2.0" apply false
    // Плагин языка Kotlin версии 1.9.24 для компиляции всех наших .kt файлов
    id("org.jetbrains.kotlin.android") version "1.9.24" apply false
    // Плагин KAPT для генерации кода Room — его версия обязательно должна совпадать с версией Kotlin (1.9.24)
    id("org.jetbrains.kotlin.kapt") version "1.9.24" apply false
}